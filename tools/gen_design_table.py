#!/usr/bin/env python3
"""Write src/combat/design_table.h from tools/data/designs.jsonl.

Refresh the data after a game patch: run tools/bots/design-dump as a bot in the cambc
workspace (`cambc run design-dump starter-cpp --rounds 20`), take the unique `DESIGN ...`
lines from its stdout in the replay bundle, strip the `DESIGN ` prefix, and save them here.
"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
KINDS = {"none": "None", "attack_reset": "AttackReset", "damage": "Damage", "aoe_damage": "AoeDamage",
         "cc": "Cc", "heal": "Heal", "dash": "Dash", "shield": "Shield"}
PASSIVES = ["None", "BonusGold", "RemoteShop", "GemFocus", "SplashAttack", "HealthStrength",
            "ResetCooldownsOnKill", "Retaliation", "StunImmunity"]

def f(x): return f"{float(x)!r}f"
def b(x): return "true" if int(x) else "false"

def slot(s):
    if s["kind"] == "none": return "AbilityDesign{}"
    return ("AbilityDesign{AbilityKind::%s, %s, %s, %s, %d, %d, %s, %s, %s, %s, %s}" % (
        KINDS[s["kind"]], f(s["range"]), f(s["modifier"]), f(s["radius"]), s["cooldown"], s["duration"],
        b(s["excludes_walking"]), b(s["enhanced"]), b(s["enemies"]), b(s["self"]), b(s["allies"])))

def main():
    src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "tools/data/designs.jsonl"
    designs = sorted((json.loads(l) for l in src.read_text().splitlines() if l.strip()), key=lambda d: d["type"])
    assert [d["type"] for d in designs] == list(range(len(designs))), "need one line per champion type"
    rows = []
    for d in designs:
        rows.append("    ChampionDesign{%d, %s, %d, %d, %d, %s, %s, %s, %s, %s, %s,\n                   {%s,\n                    %s},\n                   Passive::%s},  // %s" % (
            d["type"], b(d["attack_range"] > 1), d["attack_range"], d["move"], d["vision"],
            f(d["health"]), f(d["health_growth"]), f(d["strength"]), f(d["strength_growth"]),
            f(d["focus"]), f(d["focus_growth"]), slot(d["slots"][0]), slot(d["slots"][1]),
            PASSIVES[d["passive"]], d["name"]))
    out = ROOT / "src/combat/design_table.h"
    out.write_text(
        "#pragma once\n// GENERATED by tools/gen_design_table.py from engine data; do not edit by hand.\n"
        '#include "model.h"\n\n'
        f"inline constexpr int kChampionTypeCount = {len(designs)};\n"
        "inline constexpr ChampionDesign kDesigns[kChampionTypeCount] = {\n" + "\n".join(rows) + "\n};\n\n"
        "// Indexed by cambc::champion_type value. An unknown type (a champion added in a patch before\n"
        "// this table is regenerated) gets an empty design instead of reading past the table.\n"
        "inline const ChampionDesign& design_for(int type) {\n"
        "    static const ChampionDesign unknown{};\n"
        "    return type >= 0 && type < kChampionTypeCount ? kDesigns[type] : unknown;\n"
        "}\n")
    print(f"wrote {out} ({len(designs)} champions)")

if __name__ == "__main__":
    main()
